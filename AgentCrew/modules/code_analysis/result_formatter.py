from typing import Any

from .file_tree_formatter import FileTreeFormatter
from .text_map_formatter import TextMapFormatter


def _count_nodes_in_structure(structure: dict[str, Any], node_types: set[str]) -> int:
    """Recursively count nodes of specific types in the tree structure."""
    count = 0
    if structure.get("type") in node_types:
        count += 1
    for child in structure.get("children", []):
        count += _count_nodes_in_structure(child, node_types)
    return count


def format_single_file_analysis(
    path: str,
    structure: dict[str, Any] | None,
    class_types: set[str],
    function_types: set[str],
) -> str:
    """Format a single file's Tree-sitter structure into compact text for caching.

    Uses ``TextMapFormatter._get_file_code_content`` internally to produce
    the same compact representation that appears in the final output, but
    without the directory-tree indentation.  The output is indented relative
    to the file (2 spaces per level) so it can be inserted under any tree
    depth during reconstruction.

    Returns a multi-line string with the file path as header:

        main.py
          class Application
            run()
    """
    from .text_map_formatter import TextMapFormatter

    fmt = TextMapFormatter()
    lines = [path]
    if structure:
        result = {"path": path, "structure": structure}
        file_lines = fmt._get_file_code_content(result, file_indent="")
        lines.extend(file_lines)
    return "\n".join(lines)


def reconstruct_from_files(
    files: dict[str, dict],
    file_tree_formatter: FileTreeFormatter | None = None,
    max_files_to_analyze: int = 150,
) -> str:
    """Reconstruct the full repository analysis output from a unified ``files`` map.

    The ``files`` map entries are:
    * ``{"hash": "...", "analysis": "..."}`` — analyzed file with compact
      per-file formatted result (includes ``classes``, ``functions``,
      ``decorated`` keys for count metadata).
    * ``{"hash": "...", "error": "..."}`` — file that produced a parse error.
    * ``{"hash": "..."}`` — hash-only (supported but not analyzed).

    Returns the same format as ``format_analysis_results`` so callers can
    use either path interchangeably.
    """
    if file_tree_formatter is None:
        file_tree_formatter = FileTreeFormatter()

    # Separate records
    analyzed: list[tuple[str, dict]] = []
    errors: list[tuple[str, str]] = []
    skipped: list[str] = []

    total_classes = 0
    total_functions = 0
    total_decorated = 0

    for path in sorted(files):
        rec = files[path]
        if "error" in rec:
            errors.append((path, rec["error"]))
            analyzed.append((path, rec))
        elif "analysis" in rec:
            analyzed.append((path, rec))
            total_classes += rec.get("classes", 0)
            total_functions += rec.get("functions", 0)
            total_decorated += rec.get("decorated", 0)
        else:
            skipped.append(path)

    sections = []

    # Summary line
    error_count = len(errors)
    total_analyzed = len(analyzed)
    sections.append(
        f"files: {total_analyzed} classes: {total_classes} "
        f"funcs: {total_functions} decorated: {total_decorated} errors: {error_count}"
    )
    if skipped:
        total_all = total_analyzed + len(skipped)
        sections.append(f"skipped: {len(skipped)} supported: {total_all}")

    # Errors section
    if errors:
        sections.append("errors:")
        for path, err in errors:
            first_line = err.split("\n")[0]
            sections.append(f"{path}: {first_line}")

    # Directory tree with per-file analyses
    # Build a tree of analyzed files
    tree: dict[str, Any] = {}
    analysis_by_path = {}
    for path, rec in analyzed:
        parts = path.replace("\\", "/").split("/")
        current = tree
        for i, part in enumerate(parts):
            if i == len(parts) - 1:
                current[part] = None  # leaf marker
                analysis_by_path[path] = rec.get("analysis", "")
            else:
                if part not in current:
                    current[part] = {}
                current = current[part]

    # Render tree with analysis
    # The per-file cached analysis generated by format_single_file_analysis
    # uses file_indent="" (no tree-level prefix), so its lines are indented
    # relative to the file root with 2-space structure branches.
    # We prepend the tree prefix (depth indentation) directly.
    def _render_tree(
        node: dict[str, Any],
        prefix: str = "",
        parent_path: str = "",
    ) -> list[str]:
        lines = []
        for name in sorted(node):
            subtree = node[name]
            full = f"{parent_path}/{name}" if parent_path else name
            if subtree is None:
                lines.append(f"{prefix}{name}")
                if full in analysis_by_path:
                    analysis_text = analysis_by_path[full]
                    if analysis_text:
                        analysis_lines = analysis_text.split("\n")
                        if analysis_lines:
                            # First line is the path header, skip
                            content_lines = analysis_lines[1:]
                            for cl in content_lines:
                                if cl.strip():
                                    # cached lines already have structure
                                    # indentation; prepend tree prefix
                                    lines.append(f"{prefix}{cl}")
                                else:
                                    lines.append("")
            else:
                lines.append(f"{prefix}{name}/")
                child_lines = _render_tree(subtree, prefix + "  ", full)
                lines.extend(child_lines)
        return lines

    tree_lines = _render_tree(tree)
    if tree_lines:
        sections.append("")
        sections.extend(tree_lines)

    # Skipped files section
    if skipped:
        sections.append("")
        sections.append("skipped analyzed files:")
        max_skip_show = int(max_files_to_analyze / 2)
        shown = sorted(skipped)[:max_skip_show]
        skip_tree = file_tree_formatter.build_file_tree(shown)
        skip_lines = file_tree_formatter.format_file_tree(skip_tree)
        sections.extend(skip_lines)
        if len(skipped) > max_skip_show:
            sections.append(f"...and {len(skipped) - max_skip_show} more files.")

    return "\n".join(sections)


class ResultFormatter:
    """Formats code analysis results into structured text reports."""

    def __init__(
        self,
        text_map_formatter: TextMapFormatter,
        file_tree_formatter: FileTreeFormatter,
        class_types: set[str],
        function_types: set[str],
        max_files_to_analyze: int,
    ):
        self._text_map_formatter = text_map_formatter
        self._file_tree_formatter = file_tree_formatter
        self._class_types = class_types
        self._function_types = function_types
        self._max_files_to_analyze = max_files_to_analyze

    def count_nodes(self, structure: dict[str, Any], node_types: set[str]) -> int:
        """Recursively count nodes of specific types in the tree structure."""
        return _count_nodes_in_structure(structure, node_types)

    def format_analysis_results(
        self,
        analysis_results: list[dict[str, Any]],
        analyzed_files: list[str],
        errors: list[dict[str, str]],
        non_analyzed_files: list[str] = [],
        total_supported_files: int = 0,
    ) -> str:
        """Format the analysis results into a clear text format.

        Args:
            analysis_results: list of analysis results for each file
            analyzed_files: list of files that were analyzed
            errors: list of errors encountered during analysis
            non_analyzed_files: list of files that were skipped due to file limit
            total_supported_files: Total number of supported files in the repository
        """

        total_files = len(analyzed_files)
        classes = sum(
            _count_nodes_in_structure(f["structure"], self._class_types)
            for f in analysis_results
        )
        functions = sum(
            _count_nodes_in_structure(f["structure"], self._function_types)
            for f in analysis_results
        )
        decorated_functions = sum(
            _count_nodes_in_structure(f["structure"], {"decorated_definition"})
            for f in analysis_results
        )
        error_count = len(errors)
        non_analyzed_count = len(non_analyzed_files)

        sections = []

        sections.append(
            f"files: {total_files} classes: {classes} funcs: {functions} decorated: {decorated_functions} errors: {error_count}"
        )
        if non_analyzed_count > 0:
            sections.append(
                f"skipped: {non_analyzed_count} supported: {total_supported_files}"
            )

        if errors:
            sections.append("errors:")
            for error in errors:
                error_first_line = error["error"].split("\n")[0]
                sections.append(f"{error['path']}: {error_first_line}")

        sections.append(self._text_map_formatter.generate_text_map(analysis_results))

        if non_analyzed_files:
            sections.append("skipped analyzed files:")
            max_non_analyzed_to_show = int(self._max_files_to_analyze / 2)
            non_analyzed_tree = self._file_tree_formatter.build_file_tree(
                sorted(non_analyzed_files)[:max_non_analyzed_to_show]
            )
            non_analyzed_tree_lines = self._file_tree_formatter.format_file_tree(
                non_analyzed_tree
            )
            sections.extend(non_analyzed_tree_lines)
            if len(non_analyzed_files) > max_non_analyzed_to_show:
                sections.append(
                    f"...and {len(non_analyzed_files) - max_non_analyzed_to_show} more files."
                )

        return "\n".join(sections)

    def reconstruct_output_from_files(self, files: dict[str, dict]) -> str:
        """Reconstruct the full repository analysis output from a ``files`` map.

        Delegates to the module-level ``reconstruct_from_files`` function.
        """
        return reconstruct_from_files(
            files,
            file_tree_formatter=self._file_tree_formatter,
            max_files_to_analyze=self._max_files_to_analyze,
        )
