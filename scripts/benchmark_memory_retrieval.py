def private_path(value: Path) -> Path:
    path = _path(value)
    _ignored(path)
    return path


def input_path(value: Path, public: str | None = None) -> Path:
    path = _path(value)
    if public is None or path != ASSETS / public:
        _ignored(path)
    check(path.is_file(), "input_file_missing")
    return path


def new_output(value: Path, inputs: list[Path]) -> Path:
    output = private_path(value)
    check(not output.exists() and not any(_overlap(output, value) for value in inputs), "unsafe_or_reused_output")
    _private_directory(output)
    return output


def write_text(path: Path, value: str) -> None:
    private_path(path)
    with path.open("x", encoding="utf-8") as stream:
        os.chmod(path, 0o600)
        stream.write(value)


